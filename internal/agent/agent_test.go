const (
	sec1 = "11111111111111111111111111111111"
	sec2 = "22222222222222222222222222222222"
)

func tp(s string) *time.Time {
	t, _ := time.Parse(time.RFC3339, s)
	return &t
}

func render(users ...telemtcfg.RenderUser) []byte { return telemtcfg.RenderUsersToml(users, 50) }

// Файл в формате бота: другой порядок, другой заголовок, миллисекунды в сроке.
const botFormat = `# Auto-generated by mtproxy-bot. DO NOT EDIT MANUALLY.

[access.users]
bob_2 = "22222222222222222222222222222222"
alice_1 = "11111111111111111111111111111111"

[access.user_max_tcp_conns]
bob_2 = 50
alice_1 = 50

[access.user_expirations]
bob_2 = "2027-01-02T03:04:05.000Z"
alice_1 = "2027-06-13T16:14:08.000Z"
`

func desiredTwo() []byte {
	return render(
		telemtcfg.RenderUser{Key: "alice_1", Secret: sec1, ExpiresAt: tp("2027-06-13T16:14:08Z")},
		telemtcfg.RenderUser{Key: "bob_2", Secret: sec2, ExpiresAt: tp("2027-01-02T03:04:05Z")},
	)
}

// Сравнение по смыслу: порядок, заголовок и формат срока не важны.
func TestCompareUsers_SameMeaningDifferentFormat(t *testing.T) {
	eq, diff := CompareUsers(desiredTwo(), []byte(botFormat))
	if !eq {
		t.Fatalf("одинаковые по смыслу файлы признаны разными: %s", diff)
	}
}

func TestCompareUsers_DetectsDifferences(t *testing.T) {
	onDisk := strings.Replace(botFormat, `alice_1 = "11111111111111111111111111111111"`, `alice_1 = "33333333333333333333333333333333"`, 1)
	onDisk = strings.Replace(onDisk, "[access.users]\n", "[access.users]\ncarol_3 = \""+sec1+"\"\n", 1)
	eq, diff := CompareUsers(render(
		telemtcfg.RenderUser{Key: "alice_1", Secret: sec1, ExpiresAt: tp("2027-06-13T16:14:08Z")},
		telemtcfg.RenderUser{Key: "bob_2", Secret: sec2, ExpiresAt: tp("2027-01-02T03:04:05Z")},
		telemtcfg.RenderUser{Key: "dave_4", Secret: sec2},
	), []byte(onDisk))
	if eq {
		t.Fatal("разные файлы признаны одинаковыми")
	}
	for _, want := range []string{"нет на машине: 1", "лишних на машине: 1", "отличаются: 1"} {
		if !strings.Contains(diff, want) {
			t.Fatalf("в описании расхождения нет %q: %s", want, diff)
		}
	}
}

func TestCompareUsers_ExpiryAndLimitMatter(t *testing.T) {
	onDisk := strings.Replace(botFormat, `alice_1 = "2027-06-13T16:14:08.000Z"`, `alice_1 = "2026-06-13T16:14:08.000Z"`, 1)
	if eq, _ := CompareUsers(desiredTwo(), []byte(onDisk)); eq {
		t.Fatal("другой срок не замечен")
	}
	onDisk = strings.Replace(botFormat, "alice_1 = 50", "alice_1 = 10", 1)
	if eq, _ := CompareUsers(desiredTwo(), []byte(onDisk)); eq {
		t.Fatal("другой лимит подключений не замечен")
	}
}

// fakeMaster - мастер для тестов агента.
type fakeMaster struct {
	mu       sync.Mutex
	bundle   store.Bundle
	reports  []store.ObservedReport
	requests int
}

func (m *fakeMaster) handler(t *testing.T, token, target string) http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /v1/desired", func(w http.ResponseWriter, r *http.Request) {
		m.mu.Lock()
		m.requests++
		b := m.bundle
		m.mu.Unlock()
		if r.Header.Get("Authorization") != "Bearer "+token || r.URL.Query().Get("target") != target {
			w.WriteHeader(http.StatusUnauthorized)
			return
		}
		if r.URL.Query().Get("rev") == "" {
			t.Error("агент не передал rev")
		}
		known := r.URL.Query().Get("rev")
		if b.Revision == 0 || known == itoa(b.Revision) {
			w.WriteHeader(http.StatusNotModified)
			return
		}
		_ = json.NewEncoder(w).Encode(b)
	})
	mux.HandleFunc("POST /v1/observed", func(w http.ResponseWriter, r *http.Request) {
		var rep store.ObservedReport
		body, _ := io.ReadAll(r.Body)
		if err := json.Unmarshal(body, &rep); err != nil {
			t.Errorf("отчёт не JSON: %v", err)
		}
		m.mu.Lock()
		m.reports = append(m.reports, rep)
		m.mu.Unlock()
		w.WriteHeader(http.StatusNoContent)
	})
	return mux
}

func itoa(n int64) string {
	b, _ := json.Marshal(n)
	return string(b)
}

func newAgent(t *testing.T, masters []string, usersFile string) *Agent {
	t.Helper()
	a, err := New(Config{
		MasterURLs: masters, Token: "tok", Target: "pr2", Version: "test",
		UsersFile: usersFile, Mode: ModeCompare, Wait: 50 * time.Millisecond,
		Log: slog.New(slog.NewTextHandler(io.Discard, nil)),
	})
	if err != nil {
		t.Fatal(err)
	}
	return a
}

// Режим «только сравнить»: агент получает бандл, сравнивает с файлом на диске,
// отчитывается и НИЧЕГО не пишет.
func TestAgent_CompareModeReportsAndNeverWrites(t *testing.T) {
	dir := t.TempDir()
	file := filepath.Join(dir, "users.toml")
	if err := os.WriteFile(file, []byte(botFormat), 0o600); err != nil {
		t.Fatal(err)
	}
	before, _ := os.Stat(file)

	m := &fakeMaster{bundle: store.Bundle{Target: "pr2", Revision: 7, Resources: []store.Desired{
		{Resource: store.ResourceTelemtUsers, Revision: 7, SHA256: telemtcfg.SHA256(desiredTwo()), Content: desiredTwo()},
	}}}
	srv := httptest.NewServer(m.handler(t, "tok", "pr2"))
	defer srv.Close()

	a := newAgent(t, []string{srv.URL}, file)
	rev, err := a.RunOnce(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if rev != 7 {
		t.Fatalf("агент должен запомнить ревизию 7, а помнит %d", rev)
	}
	if len(m.reports) != 1 {
		t.Fatalf("ждали один отчёт, получили %d", len(m.reports))
	}
	r := m.reports[0].Resources[0]
	if m.reports[0].Target != "pr2" || r.Status != "compared" || r.Revision != 7 || r.Error != "" {
		t.Fatalf("неверный отчёт: %+v", m.reports[0])
	}
	got, _ := os.ReadFile(file)
	after, _ := os.Stat(file)
	if string(got) != botFormat || !after.ModTime().Equal(before.ModTime()) {
		t.Fatal("в режиме сравнения агент изменил файл")
	}

	// Следующий цикл: ревизия та же - мастер отвечает 304, нового отчёта нет.
	if _, err := a.RunOnce(context.Background()); err != nil {
		t.Fatal(err)
	}
	if len(m.reports) != 1 {
		t.Fatalf("без новой ревизии и без перепроверки лишний отчёт: %d", len(m.reports))
	}
}

// Расхождение и отсутствие файла попадают в отчёт.
func TestAgent_ReportsDriftAndMissingFile(t *testing.T) {
	dir := t.TempDir()
	file := filepath.Join(dir, "users.toml")
	m := &fakeMaster{bundle: store.Bundle{Target: "pr2", Revision: 3, Resources: []store.Desired{
		{Resource: store.ResourceTelemtUsers, Revision: 3, SHA256: "x", Content: desiredTwo()},
	}}}
	srv := httptest.NewServer(m.handler(t, "tok", "pr2"))
	defer srv.Close()

	a := newAgent(t, []string{srv.URL}, file)
	if _, err := a.RunOnce(context.Background()); err != nil {
		t.Fatal(err)
	}
	if r := m.reports[0].Resources[0]; r.Status != "failed" || !strings.Contains(r.Error, "users.toml") {
		t.Fatalf("нет файла: ждали failed с причиной, получили %+v", r)
	}

	if err := os.WriteFile(file, []byte(strings.Replace(botFormat, "bob_2", "zed_9", -1)), 0o600); err != nil {
		t.Fatal(err)
	}
	a.ForceRecheck()
	if _, err := a.RunOnce(context.Background()); err != nil {
		t.Fatal(err)
	}
	last := m.reports[len(m.reports)-1].Resources[0]
	if last.Status != "compared" || last.Error == "" {
		t.Fatalf("расхождение должно быть в отчёте, получили %+v", last)
	}
}

// Первый мастер недоступен - агент идёт ко второму.
func TestAgent_FallsBackToNextMaster(t *testing.T) {
	dir := t.TempDir()
	file := filepath.Join(dir, "users.toml")
	_ = os.WriteFile(file, []byte(botFormat), 0o600)
	dead := httptest.NewServer(http.NotFoundHandler())
	deadURL := dead.URL
	dead.Close()

	m := &fakeMaster{bundle: store.Bundle{Target: "pr2", Revision: 2, Resources: []store.Desired{
		{Resource: store.ResourceTelemtUsers, Revision: 2, SHA256: "x", Content: desiredTwo()},
	}}}
	srv := httptest.NewServer(m.handler(t, "tok", "pr2"))
	defer srv.Close()

	a := newAgent(t, []string{deadURL, srv.URL}, file)
	rev, err := a.RunOnce(context.Background())
	if err != nil || rev != 2 {
		t.Fatalf("ждали ревизию 2 через второй мастер, получили %d, %v", rev, err)
	}
}

