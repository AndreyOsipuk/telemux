func TestMergeOverlay_ArrayReplacesWholeGroup(t *testing.T) {
	ov := "[[server.listeners]]\nip = \"127.0.0.1\"\n\n[[server.listeners]]\nip = \"::1\"\n"
	out, err := MergeOverlay(baseConfig, ov)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Count(out, "[[server.listeners]]") != 2 || strings.Contains(out, "198.51.100.10") {
		t.Errorf("группа [[server.listeners]] не заменена целиком:\n%s", out)
	}
	// Место группы сохранено: listeners до [censorship].
	if strings.Index(out, "[[server.listeners]]") > strings.Index(out, "[censorship]") {
		t.Errorf("группа уехала в конец:\n%s", out)
	}
}

