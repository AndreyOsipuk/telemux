// norm - набор значимых строк без пустых и комментариев: порядок ключей внутри
// секции после сборки может отличаться от ручного файла.
func norm(s string) string {
	var out []string
	for _, l := range strings.Split(s, "\n") {
		l = strings.TrimSpace(l)
		if l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		out = append(out, l)
	}
	return strings.Join(out, "\n")
}

// Параметры профилей (secret_mode, лимиты) - машинные: на WEB-релее они свои. Сборка
// берёт их из профилей текущего telemt.toml, а не по умолчанию, иначе первое же
// применение telemt.config переписало бы ee на dd у всех пользователей релея.
func TestComposeMainConfigFrom_KeepsProfileTemplate(t *testing.T) {
	current, _ := ComposeMainConfig(baseConfig, webOverlay, []string{"sub_1"})
	current = strings.NewReplacer(`secret_mode = "dd"`, `secret_mode = "ee"`, "max_sessions = 8", "max_sessions = 4").Replace(current)
	out, err := ComposeMainConfigFrom(baseConfig, webOverlay, current, []string{"sub_1", "sub_2"})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Count(out, `secret_mode = "ee"`) != 2 || strings.Count(out, "max_sessions = 4") != 2 || strings.Contains(out, `"dd"`) {
		t.Errorf("шаблон профилей машины потерян:\n%s", out)
	}
	// Та же сборка без изменений - текст машины байт в байт (нет перезагрузки по кругу).
	same, err := ComposeMainConfigFrom(baseConfig, webOverlay, current, []string{"sub_1"})
	if err != nil || same != current {
		t.Errorf("сборка из тех же частей изменила конфиг машины: %v\n%s", err, same)
	}
	// Пустой список: старый профиль не протаскивается в результат.
	empty, err := ComposeMainConfigFrom(baseConfig, webOverlay, current, nil)
	if err != nil || strings.Contains(empty, profileHeader) {
		t.Errorf("при пустом списке остался профиль: %v\n%s", err, empty)
	}
}

// Комментарий с заголовком профиля не подменяет образец: шаблон берётся из настоящего блока.
