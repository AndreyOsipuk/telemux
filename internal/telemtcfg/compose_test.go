func TestMergeOverlay_ReplacesKeysKeepsRest(t *testing.T) {
	out, err := MergeOverlay(baseConfig, webOverlay)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"port = 8453",
		`ip = "127.0.0.1"`,
		`announce_ip = "203.0.113.7"`,
		"mask_port = 8444",
		`tls_front_dir = "/var/lib/telemt-relay/tlsfront"`,
		"[web]",
		"[[web.vhosts]]",
		`include = "/etc/telemt/users.toml"`, // база осталась
		`tls_domain = "example.com"`,
		"fast_mode = true",
		`"::1/128",`, // многострочный массив не порван
	} {
		if !strings.Contains(out, want) {
			t.Errorf("нет %q в результате:\n%s", want, out)
		}
	}
	for _, gone := range []string{"port = 443\n", `announce_ip = "198.51.100.10"`, `ip = "0.0.0.0"`, "mask_port = 443", "/var/lib/telemt/tlsfront"} {
		if strings.Contains(out, gone) {
			t.Errorf("осталось %q из базы, хотя машина его переопределила:\n%s", gone, out)
		}
	}
	// Ключ, которого в машинной части нет, остаётся в своей секции.
	if strings.Count(out, "[server]") != 1 || strings.Count(out, "[censorship]") != 1 {
		t.Errorf("секции задвоились:\n%s", out)
	}
	if !strings.HasSuffix(out, "\n") {
		t.Error("нет перевода строки в конце")
	}
}

func TestMergeOverlay_EmptyOverlayIsIdentity(t *testing.T) {
	out, err := MergeOverlay(baseConfig, "")
	if err != nil {
		t.Fatal(err)
	}
	if out != baseConfig {
		t.Errorf("пустая машинная часть изменила базу:\n%s", out)
	}
	out, err = MergeOverlay(baseConfig, "# только комментарий\n\n")
	if err != nil || out != baseConfig {
		t.Errorf("комментарий изменил базу: %v\n%s", err, out)
	}
}

