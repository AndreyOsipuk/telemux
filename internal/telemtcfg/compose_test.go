func TestGuardMainConfig(t *testing.T) {
	webCur, _ := ComposeMainConfig(baseConfig, webOverlay, []string{"a"})
	if err := GuardMainConfig(webCur, baseConfig, "/etc/telemt/users.toml"); err == nil || !strings.Contains(err.Error(), "WEB") {
		t.Errorf("потеря WEB-режима не поймана: %v", err)
	}
	if err := GuardMainConfig(baseConfig, webCur, "/etc/telemt/users.toml"); err != nil {
		t.Errorf("включение WEB отвергнуто: %v", err)
	}
	if err := GuardMainConfig(baseConfig, baseConfig, "/srv/telemt/users.toml"); err == nil {
		t.Error("include не на users.toml агента - пользователи пропали бы")
	}
	if err := GuardMainConfig(baseConfig, baseConfig, ""); err != nil {
		t.Errorf("без users.toml агента include не проверяется: %v", err)
	}
	apiOff := strings.Replace(baseConfig, "read_only = true", "read_only = true\nenabled = false", 1)
	if err := GuardMainConfig(baseConfig, apiOff, "/etc/telemt/users.toml"); err == nil {
		t.Error("выключенный API принят - агенту нечем проверить применение")
	}
}

func TestDeriveOverlay_RoundTrip(t *testing.T) {
	// На машине сейчас база + ручные правки + профили.
	current, err := ComposeMainConfig(baseConfig, webOverlay, []string{"sub_1"})
	if err != nil {
		t.Fatal(err)
	}
	current = strings.Replace(current, "tg_connect = 10", "tg_connect = 10\n# руками\nntp_check = false", 1)
	ov, warns := DeriveOverlay(baseConfig, current)
	if strings.Contains(ov, profileHeader) {
		t.Errorf("профили попали в машинную часть:\n%s", ov)
	}
	if strings.Contains(ov, "tls_domain") || strings.Contains(ov, "[[upstreams]]") {
		t.Errorf("совпадающее с базой попало в машинную часть:\n%s", ov)
	}
	if len(warns) != 0 {
		t.Errorf("лишние предупреждения: %v", warns)
	}
	got, err := ComposeMainConfig(baseConfig, ov, []string{"sub_1"})
	if err != nil {
		t.Fatal(err)
	}
	if norm(got) != norm(current) {
		t.Errorf("база + выведенная машинная часть != конфиг на машине\n--- машинная часть\n%s\n--- собрано\n%s\n--- на машине\n%s", ov, got, current)
	}
}

